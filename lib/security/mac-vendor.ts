/** Normalizes a MAC address string to `AA:BB:CC` uppercase colon form for the first 3 octets. */
function normalizeOuiPrefix(mac: string): string | null {
  const hex = mac.replace(/[^0-9a-fA-F]/g, "").toUpperCase()
  if (hex.length < 6) return null
  const octets = hex.slice(0, 6).match(/.{2}/g)
  if (!octets || octets.length !== 3) return null
  return octets.join(":")
}

/**
 * Resolves a device vendor name from the first 3 octets (OUI) of a MAC
 * address. Accepts any common MAC formatting (colons, hyphens, dots, no
 * separators) and is case-insensitive. Returns `null` — never "Unknown" —
 * when the prefix isn't in the curated table, so the UI can render its own
 * fallback consistently.
 */
export function lookupMacVendor(mac: string): string | null {
  if (!mac) return null
  const prefix = normalizeOuiPrefix(mac)
  if (!prefix) return null
  return OUI_VENDOR_MAP[prefix] ?? null
}
